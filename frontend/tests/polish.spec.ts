import {test,expect} from '@playwright/test';
import {selectProfile} from './profile-helpers';
test('clear product journey, explicit demo switch, and confirmed-deal navigation',async({page})=>{
 await page.goto('/');await selectProfile(page,'Abbhijit');
 await expect(page.getByRole('heading',{name:'Your campus.'})).toBeVisible();
 await expect(page.getByRole('region',{name:'How SwApStEr works'}).locator('h3')).toHaveCount(4);
 await page.getByRole('button',{name:'Explore Marketplace',exact:true}).click();
 await expect(page.getByRole('textbox',{name:'Search marketplace'})).toBeInViewport();
 await page.getByRole('button',{name:'See AI Negotiation Demo',exact:true}).click();
 await expect(page.getByRole('dialog')).toBeVisible();
 await page.getByRole('button',{name:'Start AI negotiation'}).click();
 await expect(page.getByRole('button',{name:'Approve Deal'})).toBeVisible({timeout:30000});
 await expect(page.locator('.agent-card').first()).toContainText('Find the best acceptable deal');
 await expect(page.locator('.seller-agent')).toContainText('Negotiate favorable terms');
 await expect(page.getByRole('progressbar',{name:'Negotiation turns'})).toHaveAttribute('aria-valuenow','4');
 await expect(page.locator('.offer-facts')).toHaveCount(4);
 await page.getByRole('button',{name:'Approve Deal'}).click();
 await expect(page.getByText('Demo mode only. In the real app, the other student approves from their own account.')).toBeVisible();
 await page.getByRole('button',{name:'Demo: Switch to seller',exact:true}).click();
 await expect(page.getByRole('heading',{name:'Deal confirmed! Both students approved.'})).toHaveCount(0);
 await page.getByRole('button',{name:'Approve Deal'}).click();
 await expect(page.getByRole('heading',{name:'Deal confirmed! Both students approved.'})).toBeVisible();
 await page.locator('.terminal-navigation').getByRole('button',{name:'View My Negotiations'}).click();
 await expect(page.getByRole('heading',{name:'My negotiations',exact:true})).toBeVisible();
 await page.getByRole('button',{name:'Back to marketplace',exact:true}).click();
 await expect(page.getByRole('heading',{name:'Your campus.'})).toBeVisible();
 await page.screenshot({path:'../artifacts/polished-marketplace.png',fullPage:true});
});
test('mobile profile dialog retains keyboard focus and readable layout',async({page})=>{
 await page.setViewportSize({width:390,height:844});await page.goto('/');await selectProfile(page,'Oumar');
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBeTruthy();
 await page.getByLabel('Demo student',{exact:true}).selectOption('__new__');
 const dialog=page.getByRole('dialog');await expect(dialog).toBeVisible();
 await page.getByRole('button',{name:'Close dialog'}).focus();await page.keyboard.press('Shift+Tab');
 await expect(page.getByRole('button',{name:'Create and select profile'})).toBeFocused();
 await page.keyboard.press('Tab');await expect(page.getByRole('button',{name:'Close dialog'})).toBeFocused();
 await page.keyboard.press('Escape');await expect(dialog).toHaveCount(0);
 await page.screenshot({path:'../artifacts/polished-mobile.png',fullPage:true});
});
