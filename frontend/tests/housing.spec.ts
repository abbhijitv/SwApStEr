import {test,expect} from '@playwright/test';
import {selectProfile} from './profile-helpers';
const disclaimer="This agreement records the students' proposed terms only. Any sublease remains subject to landlord or property-manager approval, applicable lease restrictions, and required documentation.";
test('housing listing, monthly negotiation, two approvals, failure, and mobile layout',async({page,browser})=>{
 const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('/');await selectProfile(page,'Shorya Moses');
 await page.getByRole('button',{name:'List an item',exact:true}).click();
 await page.getByRole('combobox',{name:'Category',exact:true}).selectOption('Housing & Subleases');
 const title='Summer campus sublease '+Date.now();
 await page.getByLabel('Housing listing title',{exact:true}).fill(title);
 await page.getByLabel('Description',{exact:true}).fill('Furnished summer room near campus, available for student sublease.');
 await page.getByLabel('Monthly asking rent ($)',{exact:true}).fill('900');
 await page.getByLabel('Private minimum monthly rent ($)',{exact:true}).fill('750');
 await page.getByLabel('Location or neighborhood',{exact:true}).fill('Tempe campus');
 await page.getByLabel('Lease start date',{exact:true}).fill('2027-05-15');
 await page.getByLabel('Lease end date',{exact:true}).fill('2027-08-15');
 await page.getByRole('button',{name:'Publish campus listing'}).click();
 await expect(page.getByRole('button',{name:title,exact:true})).toBeVisible();
 await page.getByRole('button',{name:'Housing & Subleases',exact:true}).click();
 const card=page.locator('.item-card').filter({hasText:title});
 await expect(card).toContainText('$900/month');await expect(card).toContainText('May 15, 2027');
 await selectProfile(page,'Abbhijit');
 await page.getByRole('button',{name:title,exact:true}).click();
 await expect(page.getByText(disclaimer,{exact:true})).toBeVisible();
 await page.getByRole('button',{name:'Let My AI Negotiate'}).click();
 await expect(page.getByLabel('Target price ($)',{exact:true})).toHaveCount(0);
 await page.getByLabel('Private maximum monthly rent ($)',{exact:true}).fill('850');
 await page.getByLabel('Desired move-in date',{exact:true}).fill('2027-06-01');
 await page.getByLabel('Desired move-out date',{exact:true}).fill('2027-08-01');
 await page.getByRole('button',{name:'Start AI negotiation'}).click();
 await expect(page.getByRole('button',{name:'Approve Deal',exact:true})).toBeVisible({timeout:30000});
 await expect(page.locator('.deal-price')).toContainText('/month');
 await expect(page.locator('.summary')).toContainText('Furnished');
 await expect(page.locator('.deal-panel')).not.toContainText('inspect the item');
 await expect(page.locator('.deal-panel')).toContainText('Jun 1, 2027 – Aug 1, 2027');
 await expect(page.locator('.transcript')).not.toContainText('850');
 await expect(page.locator('.deal-panel')).toContainText(disclaimer);
 const url=page.url();
 await page.getByRole('button',{name:'Approve Deal',exact:true}).click();
 await expect(page.getByText('You approved this deal.',{exact:true})).toBeVisible();
 const context=await browser.newContext();
 try{
  const seller=await context.newPage();await seller.goto('/');await selectProfile(seller,'Shorya Moses');await seller.goto(url);
  await seller.getByRole('button',{name:'Approve Deal',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Housing terms mutually accepted.',exact:true})).toBeVisible({timeout:10000});
 }finally{await context.close()}
 await page.screenshot({path:'../artifacts/housing-desktop.png',fullPage:true});
 await page.setViewportSize({width:390,height:844});
 await page.screenshot({path:'../artifacts/housing-mobile.png',fullPage:true});
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBeTruthy();
 await page.getByRole('button',{name:'Back to Marketplace',exact:true}).click();
 await page.getByRole('button',{name:title,exact:true}).click();
 await page.getByRole('button',{name:'Let My AI Negotiate'}).click();
 await page.getByLabel('Private maximum monthly rent ($)',{exact:true}).fill('700');
 await page.getByRole('button',{name:'Start AI negotiation'}).click();
 await expect(page.locator('.outcome.failure')).toContainText('No agreement',{timeout:30000});
 await expect(page.getByRole('button',{name:'Approve Deal',exact:true})).toHaveCount(0);
 expect(errors).toEqual([]);
});
